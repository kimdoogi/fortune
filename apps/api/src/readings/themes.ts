  "가족과 나누지 못한 이야기",
  "잠과 하루 생활 리듬",
  "몸 쓰기: 걷기·운동·스트레칭",
  "요리나 먹는 것",
  "반려동물이나 키우는 식물",
  "동네와 자주 가는 곳",
